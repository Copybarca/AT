--changeset copybarca:002-pipeline-processes-and-extraction splitStatements:true endDelimiter:;
CREATE SCHEMA IF NOT EXISTS "scheduled-processes";

ALTER TABLE trans.segment
    ADD COLUMN IF NOT EXISTS physical_page INTEGER,
    ADD COLUMN IF NOT EXISTS bbox_json TEXT,
    ADD COLUMN IF NOT EXISTS style VARCHAR(32),
    ADD COLUMN IF NOT EXISTS translatable BOOLEAN NOT NULL DEFAULT TRUE;

ALTER TABLE trans.insertion
    ADD COLUMN IF NOT EXISTS media_type VARCHAR(64),
    ADD COLUMN IF NOT EXISTS checksum VARCHAR(80);

CREATE TABLE IF NOT EXISTS trans.insertion_text_region (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    insertion_id BIGINT NOT NULL,
    stable_key VARCHAR(64) NOT NULL,
    original_text_hash TEXT NOT NULL,
    sequential_number INTEGER NOT NULL,
    pixel_bbox_json TEXT NOT NULL,
    ocr_confidence NUMERIC(5, 2),
    CONSTRAINT insertion_text_region_pkey PRIMARY KEY (id),
    CONSTRAINT fk_insertion_text_region_insertion
        FOREIGN KEY (insertion_id) REFERENCES trans.insertion (id) ON DELETE CASCADE,
    CONSTRAINT fk_insertion_text_region_text
        FOREIGN KEY (original_text_hash) REFERENCES trans.text_segment (text_hash)
        ON DELETE RESTRICT,
    CONSTRAINT uq_insertion_text_region_stable_key UNIQUE (stable_key),
    CONSTRAINT uq_insertion_text_region_order
        UNIQUE (insertion_id, sequential_number)
);

CREATE TABLE IF NOT EXISTS "scheduled-processes".pdf_extraction_process (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    book_id BIGINT NOT NULL,
    status VARCHAR(16) NOT NULL,
    pdf_sha256 VARCHAR(80),
    extractor_version VARCHAR(64),
    expected_segment_count INTEGER,
    expected_image_count INTEGER,
    expected_region_count INTEGER,
    started_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    completed_at TIMESTAMPTZ,
    CONSTRAINT pdf_extraction_process_pkey PRIMARY KEY (id),
    CONSTRAINT fk_pdf_extraction_book
        FOREIGN KEY (book_id) REFERENCES trans.book (id) ON DELETE CASCADE,
    CONSTRAINT chk_pdf_extraction_status
        CHECK (status IN ('IN_PROGRESS', 'COMPLETED')),
    CONSTRAINT uq_pdf_extraction_book UNIQUE (book_id)
);

CREATE TABLE IF NOT EXISTS "scheduled-processes".translation_process (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    book_id BIGINT NOT NULL,
    target_language VARCHAR(32) NOT NULL,
    status VARCHAR(16) NOT NULL,
    started_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    completed_at TIMESTAMPTZ,
    CONSTRAINT translation_process_pkey PRIMARY KEY (id),
    CONSTRAINT fk_translation_process_book
        FOREIGN KEY (book_id) REFERENCES trans.book (id) ON DELETE CASCADE,
    CONSTRAINT chk_translation_process_status
        CHECK (status IN ('IN_PROGRESS', 'COMPLETED')),
    CONSTRAINT uq_translation_process_book_language
        UNIQUE (book_id, target_language)
);

CREATE TABLE IF NOT EXISTS "scheduled-processes".pdf_build_process (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    book_id BIGINT NOT NULL,
    target_language VARCHAR(32) NOT NULL,
    status VARCHAR(16) NOT NULL,
    started_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    completed_at TIMESTAMPTZ,
    CONSTRAINT pdf_build_process_pkey PRIMARY KEY (id),
    CONSTRAINT fk_pdf_build_book
        FOREIGN KEY (book_id) REFERENCES trans.book (id) ON DELETE CASCADE,
    CONSTRAINT chk_pdf_build_status
        CHECK (status IN ('IN_PROGRESS', 'COMPLETED')),
    CONSTRAINT uq_pdf_build_book_language
        UNIQUE (book_id, target_language)
);

CREATE INDEX IF NOT EXISTS idx_insertion_text_region_insertion
    ON trans.insertion_text_region (insertion_id);
CREATE INDEX IF NOT EXISTS idx_insertion_text_region_source_hash
    ON trans.insertion_text_region (original_text_hash);

